import '../data/notifiers.dart';

class AppTranslations {
  static String translate(String key) {
    final lang = selectedLanguageNotifier.value;
    if (_translations[lang] != null && _translations[lang]![key] != null) {
      return _translations[lang]![key]!;
    }
    // Fallback to English
    return _translations['English']?[key] ?? key;
  }

  static String getTranslationMeaning(Map<String, dynamic> data, String currentLang) {
    bool isValid(dynamic val) {
      if (val == null) return false;
      final s = val.toString().trim();
      return s.isNotEmpty && s != 'N/A' && s.toLowerCase() != 'null';
    }

    // 1. Try language-specific field from database
    final langField = 'Meaning$currentLang';
    if (isValid(data[langField])) {
      return data[langField].toString();
    }

    // 2. Try MeaningUser if SavedLanguage matches currentLang
    if (data['SavedLanguage'] == currentLang && isValid(data['MeaningUser'])) {
      return data['MeaningUser'].toString();
    }

    // 3. Fallback to English
    if (isValid(data['MeaningEnglish'])) {
      return data['MeaningEnglish'].toString();
    }

    // 4. Fallback to Arabic
    if (isValid(data['MeaningArabic'])) {
      return data['MeaningArabic'].toString();
    }

    // 5. Fallback to default Meaning
    if (isValid(data['Meaning'])) {
      return data['Meaning'].toString();
    }

    return 'No Meaning';
  }

